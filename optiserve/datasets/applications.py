"""Benchmark application definitions.

Currently provides App3 — the committed 3-function workflow (``f1 -> resnet ->
yolo`` with a back-edge and a self-loop) used in the evaluation — plus a generic
helper for assembling ML workflows from cached performance models.

NOTE: only App3's graph/formula is defined in the repository. App1/2/4/5/6 were
produced by manually editing the evaluation notebook and their graph, variant,
and accuracy-formula definitions are not committed anywhere; they must be
supplied to reproduce the full experiment set.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from pathlib import Path

from optiserve.modeling.parametric import ParamFunction
from optiserve.workflow import ModelVariant, WorkflowGraph

# App3 configuration (from experiments/test_optimization.ipynb).
_RESNET_VARIANTS = ["resnet-18", "resnet-34", "resnet-50", "resnet-101"]
_YOLO_VARIANTS = ["yolov10n", "yolov10s", "yolov10m", "yolov10l"]
_F1_GRID = list(range(128, 3072, 192))
_RESNET_GRID = list(range(2048, 10000, 512))
_YOLO_GRID = list(range(2048, 10000, 800))

# End-to-end accuracy weights resnet (a1) x2 and yolo (a2); f1 (a0) is non-ML.
APP3_ACCURACY_FORMULA: Callable = lambda a0, a1, a2: 2 * a1 + a2  # noqa: E731


#: Environment variable pointing at the .mdl cache, so a deployed or
#: containerised run can mount it anywhere.
MODELS_DIR_ENV = "OPTISERVE_MODELS_DIR"
_DEFAULT_MODELS_DIRNAME = "modeled_functions"


def resolve_models_dir(models_dir: str | Path | None = None) -> Path:
    """Locate the ``modeled_functions/`` cache.

    Resolution order: the explicit argument, then ``$OPTISERVE_MODELS_DIR``,
    then ``./modeled_functions``, then ``modeled_functions/`` beside the
    installed package.

    The cache is a load-bearing input that is *gitignored* and cannot be
    regenerated without live AWS, so the previous bare
    ``Path("modeled_functions")`` meant this entry point worked only when the
    process happened to be started from the repository root — an installed
    package or a container with a different working directory silently got a
    ``FileNotFoundError`` naming a relative path that told the user nothing.
    """
    # An explicit argument is authoritative: falling back when the caller named
    # a directory would silently load a *different* set of fitted curves than
    # the one they asked for.
    if models_dir is not None:
        explicit = Path(models_dir)
        if not explicit.is_dir():
            raise FileNotFoundError(
                f"models_dir {explicit} does not exist. Omit the argument to fall "
                f"back to ${MODELS_DIR_ENV}, ./{_DEFAULT_MODELS_DIRNAME}, or the "
                "directory beside the installed package."
            )
        return explicit

    candidates: list[Path] = []
    env_value = os.environ.get(MODELS_DIR_ENV)
    if env_value:
        candidates.append(Path(env_value))
    candidates.append(Path.cwd() / _DEFAULT_MODELS_DIRNAME)
    candidates.append(Path(__file__).resolve().parent.parent.parent / _DEFAULT_MODELS_DIRNAME)

    for candidate in candidates:
        if candidate.is_dir():
            return candidate

    raise FileNotFoundError(
        "Could not locate the cached performance-model directory. Looked in: "
        + ", ".join(str(c) for c in candidates)
        + f". Set ${MODELS_DIR_ENV} or pass models_dir=... . The cache holds the "
        "fitted *.mdl curves and is produced by profiling against live AWS; it "
        "is not committed to the repository."
    )


def _load(models_dir: Path, name: str) -> ParamFunction:
    path = models_dir / f"{name}.mdl"
    if not path.exists():
        available = sorted(p.stem for p in models_dir.glob("*.mdl"))
        raise FileNotFoundError(
            f"Cached model {path} not found. App3 requires the modeled_functions/ "
            "cache (produced by profiling on live AWS). "
            f"Available in {models_dir}: {available or 'none'}."
        )
    try:
        return ParamFunction.load(path)
    except Exception as exc:
        # A truncated or foreign .mdl otherwise surfaces as a bare pickle
        # KeyError with no mention of the file, which is close to undebuggable
        # for a cache that is gitignored and regenerated by a separate,
        # expensive process.
        raise ValueError(
            f"Could not load the cached performance model at {path}: "
            f"{type(exc).__name__}: {exc}. The file may be truncated or written "
            "by an incompatible version; regenerate it by profiling the function."
        ) from exc


def build_app3(models_dir=None) -> tuple[WorkflowGraph, Callable]:
    """Assemble the App3 workflow from cached per-function models.

    Returns the built :class:`WorkflowGraph` and its end-to-end accuracy formula.
    """
    models_dir = resolve_models_dir(models_dir)

    f1_variants = [ModelVariant("None", _load(models_dir, "f1"))]
    resnet_variants: list[ModelVariant] = [
        ModelVariant(v, _load(models_dir, f"resnet_{v}")) for v in _RESNET_VARIANTS
    ]
    yolo_variants: list[ModelVariant] = [
        ModelVariant(v, _load(models_dir, f"yolo_{v}")) for v in _YOLO_VARIANTS
    ]

    wg = WorkflowGraph()
    wg.add_ml_function(1, f1_variants, _F1_GRID)  # f1
    wg.add_ml_function(2, resnet_variants, _RESNET_GRID)  # resnet
    wg.add_ml_function(3, yolo_variants, _YOLO_GRID)  # yolo
    wg.add_edges(
        [
            ("Start", 1, 1.0),
            (1, 2, 1.0),
            (2, 1, 0.3),
            (2, 3, 0.7),
            (3, 3, 0.2),
            (3, "End", 0.8),
        ]
    )
    return wg, APP3_ACCURACY_FORMULA
